#!/usr/bin/env bash
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT_DIR"

MANIFEST_PATH="${MANIFEST_PATH:-$ROOT_DIR/benchmarks/real-audio/manifest.json}"
BOOTSTRAP_DATASET="${BOOTSTRAP_DATASET:-diarizers-community/voxconverse}"
BOOTSTRAP_SPLIT="${BOOTSTRAP_SPLIT:-dev}"
BOOTSTRAP_CASES="${BOOTSTRAP_CASES:-1}"
BOOTSTRAP_OUT_DIR="${BOOTSTRAP_OUT_DIR:-$ROOT_DIR/benchmarks/real-audio/data}"
export MANIFEST_PATH

if [ ! -d ".venv" ]; then
  python3 -m venv .venv
fi
. .venv/bin/activate
python3 -m pip install --upgrade pip >/dev/null
python3 -m pip install --quiet datasets numpy >/dev/null

if [ ! -f "$MANIFEST_PATH" ]; then
  echo "[real-benchmark] manifest not found; bootstrapping from $BOOTSTRAP_DATASET/$BOOTSTRAP_SPLIT"
  export BOOTSTRAP_DATASET BOOTSTRAP_SPLIT BOOTSTRAP_CASES BOOTSTRAP_OUT_DIR
  python3 - <<'PY'
import json
import os
import shutil
from pathlib import Path

try:
    from datasets import Audio, load_dataset
except ImportError as exc:
    raise RuntimeError(
        "missing 'datasets' package; install with `python3 -m pip install datasets`"
    ) from exc

manifest_path = Path(os.environ["MANIFEST_PATH"])
dataset_name = os.environ["BOOTSTRAP_DATASET"]
split_name = os.environ["BOOTSTRAP_SPLIT"]
case_count = max(1, int(os.environ["BOOTSTRAP_CASES"]))
out_dir = Path(os.environ["BOOTSTRAP_OUT_DIR"])
out_dir.mkdir(parents=True, exist_ok=True)

dataset = load_dataset(dataset_name, split=f"{split_name}[:{case_count}]")
dataset = dataset.cast_column("audio", Audio(decode=False))
cases = []

for idx, row in enumerate(dataset):
    audio = row["audio"] or {}
    base = f"{dataset_name.replace('/', '_')}_{split_name}_{idx:03d}"
    source_path = audio.get("path") or ""
    suffix = Path(source_path).suffix if source_path else ".wav"
    audio_path = out_dir / f"{base}{suffix}"
    ref_path = out_dir / f"{base}.reference.json"
    local_path = Path(source_path) if source_path else None

    if local_path and local_path.exists():
        audio_path.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(local_path, audio_path)
    elif audio.get("bytes") is not None:
        audio_path.parent.mkdir(parents=True, exist_ok=True)
        audio_path.write_bytes(audio["bytes"])
    else:
        raise RuntimeError(f"unable to materialize audio for case index {idx}")

    starts = row.get("timestamps_start") or []
    ends = row.get("timestamps_end") or []
    speakers = row.get("speakers") or []
    turns = []
    for s, e, spk in zip(starts, ends, speakers):
        turns.append(
            {"start": float(s), "end": float(e), "speaker": str(spk)}
        )
    ref_path.write_text(json.dumps({"speaker_turns": turns}, indent=2))

    cases.append(
        {
            "id": base,
            "audio_path": str(audio_path.relative_to(Path.cwd())),
            "reference_path": str(ref_path.relative_to(Path.cwd())),
            "provenance": {
                "source": dataset_name,
                "split": split_name,
                "notes": "auto-generated by download-real-diarization-benchmark.sh",
            },
        }
    )

manifest = {
    "version": 1,
    "description": "Auto-generated real-audio diarization benchmark cases",
    "cases": cases,
}
manifest_path.parent.mkdir(parents=True, exist_ok=True)
manifest_path.write_text(json.dumps(manifest, indent=2))
print(f"[real-benchmark] generated manifest: {manifest_path}")
print(f"[real-benchmark] generated cases: {len(cases)}")
PY
fi

python3 - <<'PY'
import hashlib
import json
import os
import urllib.request
from pathlib import Path

from whisperx_ui_backend.benchmarking.diarization_metrics import validate_real_audio_manifest

manifest_path = Path(os.environ["MANIFEST_PATH"])
manifest = json.loads(manifest_path.read_text())
cases = validate_real_audio_manifest(manifest)

def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            h.update(chunk)
    return h.hexdigest()

def download_if_needed(url: str, target: Path) -> None:
    target.parent.mkdir(parents=True, exist_ok=True)
    if target.exists():
        return
    if not url:
        raise RuntimeError(f"missing url for {target}")
    urllib.request.urlretrieve(url, target)

for case in cases:
    download = case.get("download") or {}
    audio_path = Path(case["audio_path"])
    ref_path = Path(case["reference_path"])

    if download:
        download_if_needed(download.get("audio_url", ""), audio_path)
        download_if_needed(download.get("reference_url", ""), ref_path)

        expected_audio_sha = download.get("audio_sha256")
        expected_ref_sha = download.get("reference_sha256")
        if expected_audio_sha and sha256(audio_path) != expected_audio_sha:
            raise RuntimeError(f"audio checksum mismatch for {audio_path}")
        if expected_ref_sha and sha256(ref_path) != expected_ref_sha:
            raise RuntimeError(f"reference checksum mismatch for {ref_path}")

    if not audio_path.exists():
        raise RuntimeError(f"missing audio file: {audio_path}")
    if not ref_path.exists():
        raise RuntimeError(f"missing reference file: {ref_path}")

print(f"[real-benchmark] PASS: {len(cases)} case(s) ready")
PY
